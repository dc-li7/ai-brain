#!/usr/bin/env bash
# Tests for memory-index: the flat index, the topic tree, and the files it must
# never touch. Everything runs on a throwaway brain in a temp folder.
#   bash AI/setup/tests/test-memory-index.sh
set -uo pipefail
SRC="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"   # repo to take memory-index from
E="$(mktemp -d)"
trap 'rm -rf "$E"' EXIT
pass=0; fail=0
check() { if eval "$2"; then echo "PASS $1"; pass=$((pass+1)); else echo "FAIL $1"; fail=$((fail+1)); fi; }

B="$E/brain"; M="$B/Memory/main"; I="$M/index"
mkdir -p "$B/AI/setup" "$M"
cp "$SRC/AI/setup/memory-index" "$B/AI/setup/"
idx() { BRAIN_DIR="$B" python3 -I "$B/AI/setup/memory-index" "$@" 2>"$E/err"; }
mem() {  # mem <name> <type> [topic] [pinned]
    { printf -- '---\nname: %s\ndescription: About %s\nmetadata:\n  type: %s\n' "$1" "$1" "$2"
      [ -n "${3:-}" ] && printf '  topic: %s\n' "$3"
      [ -n "${4:-}" ] && printf '  pinned: %s\n' "$4"
      printf -- '---\nbody\n'; } > "$M/$1.md"
}
MARK='<!-- generated by memory-index: do not edit; rebuilt from the memory files and TOPICS.md -->'

# Flat mode: a scope with no TOPICS.md keeps the old one-file index.
mem m1 user work
mem m2 feedback work/clients
mem m3 project
mem m4 reference work true
idx >/dev/null; rc=$?
check "no TOPICS.md: flat index, no index/ folder" '[ $rc -eq 0 ] && grep -q "^## User" "$M/MEMORY.md" && [ ! -e "$I" ]'

# Tree mode.
printf -- '# Topics\n\n- work: Work things\n- work/clients: One client per memory\n' > "$M/TOPICS.md"
idx >/dev/null; rc=$?
check "tree: MEMORY.md lists the pinned memory, the topics with counts, and the loose one" \
    '[ $rc -eq 0 ] && grep -q "^- ★ \[m4.md\](m4.md)" "$M/MEMORY.md" && grep -q "^- \[work\](index/work.md) — Work things (3) · sub-topics: clients" "$M/MEMORY.md" && grep -q "^## No topic yet (1)" "$M/MEMORY.md" && grep -q "\[m3.md\](m3.md)" "$M/MEMORY.md"'
check "tree: TOPICS.md is not listed as a memory" '! grep -qF "[TOPICS.md](" "$M/MEMORY.md"'
check "tree: topic files carry the marker and link back to the memories" \
    '[ "$(head -1 "$I/work.md")" = "$MARK" ] && grep -q "(../m1.md)" "$I/work.md" && grep -q "(../../m2.md)" "$I/work/clients.md" && grep -q "(work/clients.md)" "$I/work.md"'
check "tree: memories with no topic get index/unsorted.md" 'grep -q "(../m3.md)" "$I/unsorted.md"'
out=$(idx)
check "a second run changes nothing" '[ -z "$out" ]'

cp "$M/MEMORY.md" "$E/before"
mem m1 user work true
out=$(idx --check)
check "--check reports the change but writes nothing" '[[ $out == *"would rebuild"* ]] && cmp -s "$M/MEMORY.md" "$E/before"'
idx >/dev/null
check "and a normal run applies it" 'grep -q "^- ★ \[m1.md\]" "$M/MEMORY.md"'

# A topic that isn't in TOPICS.md still gets listed, with a note.
mem m5 user home
idx >/dev/null
check "unknown topic: listed in its own file, with a note" 'grep -q "(../m5.md)" "$I/home.md" && grep -q "not in TOPICS.md" "$E/err"'

# Attack: a topic that tries to climb out of index/.
mem m6 user '../../../../evil'
idx >/dev/null
check "a ../ topic is filed under unsorted, nothing written outside" 'grep -q "(../m6.md)" "$I/unsorted.md" && grep -q "bad topic" "$E/err" && [ -z "$(find "$E" -name "evil*")" ]'
rm "$M/m6.md"

# Hand-written files under index/ are never deleted or overwritten.
echo "my notes" > "$I/notes.md"
idx >/dev/null
check "a hand-written file in index/ is kept" '[ "$(cat "$I/notes.md")" = "my notes" ]'
sed -i 1d "$I/work.md"; cp "$I/work.md" "$E/work.before"
idx >/dev/null; rc=$?
check "a topic file without the marker is not overwritten (and that is an error)" '[ $rc -ne 0 ] && cmp -s "$I/work.md" "$E/work.before" && grep -q "not made by memory-index" "$E/err"'
rm "$I/work.md"; idx >/dev/null

# A topic that goes away takes its generated file (and empty folder) with it.
printf -- '# Topics\n\n- work: Work things\n- home: Home things\n' > "$M/TOPICS.md"
mem m2 feedback work
idx >/dev/null
check "a removed topic's file and folder are deleted" '[ ! -e "$I/work/clients.md" ] && [ ! -e "$I/work" ] && grep -q "(../m2.md)" "$I/work.md"'

# Attack: links inside the memory folder that point somewhere else.
mkdir "$E/outside"
rm -rf "$I"; ln -s "$E/outside" "$I"
idx >/dev/null; rc=$?
check "index/ as a symlink: nothing written through it" '[ $rc -ne 0 ] && [ -z "$(ls -A "$E/outside")" ]'
rm "$I"; idx >/dev/null
printf -- '# Topics\n\n- work: Work things\n- work/clients: Clients\n' > "$M/TOPICS.md"
mem m2 feedback work/clients
ln -s "$E/outside" "$I/work"
idx >/dev/null; rc=$?
check "a linked sub-folder: nothing written through it" '[ $rc -ne 0 ] && [ -z "$(ls -A "$E/outside")" ] && [ -L "$I/work" ]'
rm "$I/work"

# Attack: a broken file never crashes the run.
printf -- '---\nname: bad\n' > "$M/bad.md"
idx >/dev/null; rc=$?
check "a memory with broken frontmatter is reported, not a crash" '[ $rc -eq 1 ] && grep -q "bad.md" "$E/err" && ! grep -q Traceback "$E/err"'

echo; echo "passed: $pass   failed: $fail"
[ "$fail" -eq 0 ]
